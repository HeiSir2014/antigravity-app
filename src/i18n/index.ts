import { createContext, useContext } from 'react';

export type LocaleCode = 'auto' | 'en' | 'zh-CN' | 'zh-TW';
export type ResolvedLocale = 'en' | 'zh-CN' | 'zh-TW';

export function resolveLocale(pref: LocaleCode): ResolvedLocale {
  if (pref !== 'auto') return pref;
  if (typeof navigator === 'undefined') return 'en';
  const lang = (navigator.language || 'en').toLowerCase();
  if (lang.startsWith('zh-tw') || lang.startsWith('zh-hk') || lang.startsWith('zh-mo') || lang.includes('hant')) {
    return 'zh-TW';
  }
  if (lang.startsWith('zh')) {
    // Covers zh-CN, zh-SG, zh-Hans
    return 'zh-CN';
  }
  return 'en';
}

