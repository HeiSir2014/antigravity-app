export type MessageKey = keyof typeof MESSAGES.en;

export interface I18nContextValue {
  locale: LocaleCode;
  resolved: ResolvedLocale;
  setLocale: (code: LocaleCode) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
  formatRelativeTime: (ms: number) => string;
}

export function createTranslator(resolved: ResolvedLocale) {
  const dict = MESSAGES[resolved] || MESSAGES.en;
  const t = (key: MessageKey, vars?: Record<string, string | number>): string => {
    let text: string = dict[key] ?? MESSAGES.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replace(`{${k}}`, String(v));
      }
    }
    return text;
  };
  const formatRelativeTime = (ms: number): string => {
    if (!ms) return t('justNow');
    const diff = Math.max(0, Math.floor((Date.now() - ms) / 1000));
    if (diff < 60) return t('justNow');
    if (diff < 3600) return t('minsAgo', { n: Math.floor(diff / 60) });
    if (diff < 86400) return t('hoursAgo', { n: Math.floor(diff / 3600) });
    return t('daysAgo', { n: Math.floor(diff / 86400) });
  };
  return { t, formatRelativeTime };
}

export const I18nContext = createContext<I18nContextValue>({
  locale: 'auto',
  resolved: 'en',
  setLocale: () => {},
  ...createTranslator('en'),
});

export function useI18n() {
  return useContext(I18nContext);
}
